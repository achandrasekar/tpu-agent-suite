"""Copy a served kernel's dispatcher and candidate kernels, in one job.

A kernel a server runs lives in the server's image, not on the agent's host,
and which kernel produced a trace name is decided by reading code that is also
only in the image: the dispatcher the op's stack frame names, and the kernels
it can build. This script runs in that image (through `compute`, beside the
server or in its environment) and copies both, so the choice can be made on
the host from files that all came from the same image in the same job.

It does not choose the kernel. It copies:

  * with `--dispatcher <file>`, the dispatcher's file (the path the stack
    frame names) and, for every module that file imports from its own
    top-level package, the files directly in that module's directory -- the
    candidate kernels and their neighbours, such as `configs.py`;
  * for every `<module>` named on the command line, the module's whole
    directory, recursively: use it for a kernel the dispatcher builds through
    a module it does not import itself.

Modules are located with `importlib.util.find_spec`, and the dispatcher is
read with `ast`: parent packages are imported, but no dispatcher or kernel
code runs and no device is touched. Every file keeps its path relative to the
`sys.path` entry it was found under (e.g.
`vllm_torchtpu/kernels/experimental/batched_rpa/kernel.py`), so copies from
different directories never collide. Bytecode caches and compiled extensions
are left out; nothing is added, renamed or edited. Standard library only.

It writes two files to the working directory:

  * `served_kernel.json`: the dispatcher and each module with the file it
    resolves to in the image and the path of its copy (`copy`), the module
    that imported it, the distribution that installs it and its version, and
    each module it imports from its own package marked present or absent in
    the copy (`imports`); the image the caller says the job ran (recorded as
    given), any import of the dispatcher that could not be located
    (`unresolved`), and every copied file with its size and sha256;
  * `served_kernel.tar.gz`: the copied files.

Usage:
    python3 introspect_kernel.py --dispatcher <file in the image> \\
        [<module>...] [--image <ref>] [--max-bytes <n>]
    python3 introspect_kernel.py <module>... [--image <ref>]

Exits 0 when both files were written, 1 when the dispatcher or a named module
could not be located or the copy would exceed `--max-bytes`. On failure,
`served_kernel.json` still holds the `error`, and no tarball is written.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import importlib.metadata
import importlib.util
import json
import sys
import tarfile
from pathlib import Path
from typing import Any

JSON_NAME = "served_kernel.json"
TAR_NAME = "served_kernel.tar.gz"

# Left out of the copy: generated by the interpreter or a compiler, not source.
SKIPPED_DIRS = frozenset({"__pycache__"})
SKIPPED_SUFFIXES = frozenset({".pyc", ".pyo", ".so", ".pyd"})

# A dispatcher and its kernels are tens of source files. Far more than this
# means a module resolved to a package root rather than a kernel.
DEFAULT_MAX_BYTES = 10 * 1024 * 1024


class IntrospectionError(Exception):
    """The copy can't be made; the message says why."""


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _is_source(path: Path, root: Path) -> bool:
    relative = path.relative_to(root)
    return (not any(part in SKIPPED_DIRS for part in relative.parts)
            and not path.is_symlink() and path.is_file()
            and path.suffix not in SKIPPED_SUFFIXES)


def source_files(directory: Path, recursive: bool) -> list[Path]:
    """Every file in `directory` that belongs in the copy, sorted."""
    paths = directory.rglob("*") if recursive else directory.iterdir()
    return sorted(path for path in paths if _is_source(path, directory))


def _search_roots() -> list[Path]:
    """`sys.path` directories, longest first, so the closest root wins."""
    roots = {Path(entry or ".").resolve() for entry in sys.path}
    return sorted((root for root in roots if root.is_dir()),
                  key=lambda root: len(root.parts),
                  reverse=True)


def import_root(path: Path) -> Path:
    """The `sys.path` entry `path` is imported from."""
    for root in _search_roots():
        if path.is_relative_to(root):
            return root
    raise IntrospectionError(f"{path} is under no sys.path entry")


def module_name(path: Path) -> str:
    """The dotted module a file under a `sys.path` entry imports as."""
    parts = list(path.relative_to(import_root(path)).with_suffix("").parts)
    if parts and parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def distribution_of(module: str) -> dict[str, str | None]:
    """The distribution that installs `module`'s top-level package."""
    top = module.split(".", 1)[0]
    names = importlib.metadata.packages_distributions().get(top) or []
    if not names:
        return {"name": None, "version": None}
    name = names[0]
    try:
        version = importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:
        version = None
    return {"name": name, "version": version}


def _spec(module: str) -> Any:
    """`module`'s spec, or None; imports its parent packages, never it."""
    try:
        return importlib.util.find_spec(module)
    except (ImportError, ValueError):
        return None


def locate(module: str) -> Path | None:
    """The file `module` resolves to in this interpreter, or None."""
    spec = _spec(module)
    if spec is None or not spec.has_location or not spec.origin:
        return None
    return Path(spec.origin).resolve()


def _is_package(module: str) -> bool:
    spec = _spec(module)
    return spec is not None and spec.submodule_search_locations is not None


def imported_modules(source: str, module: str, is_package: bool) -> list[str]:
    """Modules `source` imports from its own top-level package, deduplicated.

    Function-level imports count: dispatchers often import a kernel only when
    they build it. `from a.b import c` names `a.b.c` when `a.b` is a package
    holding a module `c`, and `a.b` otherwise. A name imported from a plain
    module is never probed as a submodule, since that would run the module.
    """
    top = module.split(".", 1)[0]
    package = module if is_package else module.rpartition(".")[0]
    found: list[str] = []

    def add(name: str) -> None:
        if name.split(".", 1)[0] == top and name not in found:
            found.append(name)

    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.Import):
            for alias in node.names:
                add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            base = node.module or ""
            if node.level:
                anchor = package.split(".")
                anchor = anchor[:len(anchor) - (node.level - 1)]
                base = ".".join(anchor + ([base] if base else []))
            if base.split(".", 1)[0] != top:
                continue
            base_is_package = _is_package(base)
            for alias in node.names:
                candidate = f"{base}.{alias.name}"
                if (alias.name != "*" and base_is_package
                        and locate(candidate) is not None):
                    add(candidate)
                else:
                    add(base)
    return found


def own_package_imports(origin: Path, module: str,
                        copied: dict[Path, Path]) -> list[dict[str, Any]]:
    """Each module `origin` imports from its own package, present or absent.

    Present means the copy holds the file the import resolves to in this
    image. An absent one is reported, never supplied: on the target, the
    import loads the image's installed module, not anything added to the copy.
    """
    try:
        source = origin.read_text(encoding="utf-8")
        names = imported_modules(source, module, origin.name == "__init__.py")
    except (OSError, SyntaxError, UnicodeDecodeError):
        return []
    imports = []
    for name in names:
        if name == module:
            continue
        located = locate(name)
        imports.append({
            "module": name,
            "present": located is not None and located in copied,
        })
    return imports


def introspect(dispatcher: str | None, modules: list[str], image: str | None,
               max_bytes: int, out_dir: Path) -> dict[str, Any]:
    """Copy the dispatcher and modules into `out_dir`, and describe them."""
    report: dict[str, Any] = {
        "image": image,
        "python": sys.executable,
        "dispatcher": None,
        "modules": [],
        "unresolved": [],
    }
    # Each copied directory once, by (directory, recursive), with its root.
    directories: dict[Path, tuple[bool, Path]] = {}
    extra_files: dict[Path, Path] = {}

    def copy_path(path: Path) -> str:
        return path.relative_to(import_root(path)).as_posix()

    def add_module(name: str, origin: Path, recursive: bool,
                   imported_by: str | None) -> None:
        root = import_root(origin)
        held = directories.get(origin.parent)
        directories[origin.parent] = (recursive
                                      or bool(held and held[0]), root)
        report["modules"].append({
            "module": name,
            "file": str(origin),
            "copy": copy_path(origin),
            "directory": str(origin.parent),
            "recursive": recursive,
            "imported_by": imported_by,
            "distribution": distribution_of(name),
        })

    try:
        if dispatcher is not None:
            path = Path(dispatcher).resolve()
            if not path.is_file():
                raise IntrospectionError(f"dispatcher {dispatcher!r} is not "
                                         "a file in this image")
            name = module_name(path)
            extra_files[path] = import_root(path)
            report["dispatcher"] = {
                "file": str(path),
                "module": name,
                "copy": copy_path(path),
                "distribution": distribution_of(name),
            }
            source = path.read_text(encoding="utf-8")
            for imported in imported_modules(source, name,
                                             path.name == "__init__.py"):
                origin = locate(imported)
                if origin is None:
                    report["unresolved"].append(imported)
                    continue
                add_module(imported, origin, False, name)
        for name in modules:
            origin = locate(name)
            if origin is None:
                raise IntrospectionError(
                    f"{name!r} is not importable in this interpreter")
            add_module(name, origin, True, None)

        files: dict[Path, Path] = dict(extra_files)
        for directory, (recursive, root) in directories.items():
            for path in source_files(directory, recursive):
                files.setdefault(path, root)
        for entry in report["modules"]:
            entry["imports"] = own_package_imports(Path(entry["file"]),
                                                   entry["module"], files)
    except IntrospectionError as exc:
        report["error"] = str(exc)
        return report

    ordered = sorted(files, key=lambda p: p.relative_to(files[p]).as_posix())
    total = sum(path.stat().st_size for path in ordered)
    report["total_bytes"] = total
    if total > max_bytes:
        report["error"] = (
            f"the copy holds {total} bytes of source, over --max-bytes "
            f"{max_bytes}: a module resolved to more than a kernel directory")
        return report
    report["files"] = [{
        "path": path.relative_to(files[path]).as_posix(),
        "bytes": path.stat().st_size,
        "sha256": _sha256(path),
    } for path in ordered]
    with tarfile.open(out_dir / TAR_NAME, "w:gz") as tar:
        for path in ordered:
            tar.add(path,
                    arcname=path.relative_to(files[path]).as_posix(),
                    recursive=False)
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("modules",
                        nargs="*",
                        help="dotted modules to copy, each with its whole "
                        "directory")
    parser.add_argument("--dispatcher",
                        help="file in the image the op's stack frame names; "
                        "copied with the modules it imports from its package")
    parser.add_argument("--image", help="image the job ran, recorded as given")
    parser.add_argument("--max-bytes",
                        type=int,
                        default=DEFAULT_MAX_BYTES,
                        help="refuse a copy larger than this")
    parser.add_argument("--out-dir",
                        type=Path,
                        default=Path("."),
                        help="where to write both files (default: cwd)")
    args = parser.parse_args(argv)
    if args.dispatcher is None and not args.modules:
        parser.error("name --dispatcher, a module, or both")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    report = introspect(args.dispatcher, args.modules, args.image,
                        args.max_bytes, args.out_dir)
    (args.out_dir / JSON_NAME).write_text(json.dumps(report, indent=2) + "\n",
                                          encoding="utf-8")
    print(json.dumps(report, indent=2))
    if "error" in report:
        print(f"ERROR: {report['error']}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
