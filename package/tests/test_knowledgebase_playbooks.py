"""Tests for knowledge base playbooks, schema validity, and link integrity."""

import re
import sys
import unittest
from pathlib import Path

import yaml

# Ensure repository root is in sys.path so 'package' can be imported
REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

KB_DIR = Path(__file__).resolve().parent.parent / "data" / "knowledgebase"
WIKI_DIR = KB_DIR / "wiki"
PLAYBOOKS_DIR = WIKI_DIR / "playbooks"
CODEBASES_DIR = WIKI_DIR / "codebases"
# The unwiring playbooks ship as tpu-knowledge-base pages, because the knowledge
# base is not copied into a build. The rest are still here, so a playbook is
# looked up across both rather than in whichever one it is in.
PAGES_DIR = (Path(__file__).resolve().parent.parent / "data" /
             "tpu-knowledge-base" / "pages")
PLAYBOOK_DIRS = (PLAYBOOKS_DIR, PAGES_DIR)


def playbooks_named(names: list[str]) -> list[tuple[str, Path | None]]:
    """Each name paired with wherever it lives, or None if it lives nowhere."""
    return [(name,
             next((d / name
                   for d in PLAYBOOK_DIRS if (d / name).is_file()), None))
            for name in names]


_HEX40 = re.compile(r"^[0-9a-f]{40}$")


def codebase_subwikis() -> list[Path]:
    """wiki/codebases/<repo>/ directories generated by wikify-repo (SCHEMA.md, "Codebase
    subwikis"). They carry wikify's own front matter (OKF 0.2) and are gated by
    `wikify finalize`, so the KB page schema is checked only at their boundary."""
    if not CODEBASES_DIR.is_dir():
        return []
    return sorted(p for p in CODEBASES_DIR.iterdir()
                  if p.is_dir() and (p / "index.md").is_file())


def in_subwiki(path: Path) -> bool:
    return any(sub in path.parents for sub in codebase_subwikis())


def kb_pages() -> list[Path]:
    """Wiki pages that follow the KB page schema: everything outside codebase subwikis and
    wikify's regenerated listing of them (wiki/codebases/index.md)."""
    listing = CODEBASES_DIR / "index.md"
    return sorted(p for p in WIKI_DIR.rglob("*.md")
                  if p != listing and not in_subwiki(p))


def frontmatter(path: Path) -> dict:
    content = path.read_text(encoding="utf-8")
    if not content.startswith("---"):
        return {}
    parts = content.split("---", 2)
    if len(parts) < 3:
        return {}
    fm = yaml.safe_load(parts[1])
    return fm if isinstance(fm, dict) else {}


class TestKnowledgeBasePlaybooks(unittest.TestCase):

    def setUp(self):
        self.assertTrue(KB_DIR.exists(),
                        f"Knowledge base dir {KB_DIR} must exist")
        self.assertTrue(PLAYBOOKS_DIR.exists(),
                        f"Playbooks dir {PLAYBOOKS_DIR} must exist")

    def test_playbooks_exist(self):
        expected_playbooks = [
            "flash-attention-to-sdpa.md",
            "mamba-ssm-unwiring.md",
            "xformers-to-sdpa.md",
            "triton-to-pytorch-ops.md",
            "apex-to-native-normalization.md",
            "deepspeed-ops-unwiring.md",
            "cuda-api-stripping-and-runtime.md",
            "tpu-distributed-and-env-hygiene.md",
            "tpu-tensor-layout-and-interp.md",
            "static-shapes-and-tracing.md",
            "huggingface-runtime-compatibility.md",
            "custom-cuda-kernel-unwiring.md",
        ]
        for name, path in playbooks_named(expected_playbooks):
            self.assertIsNotNone(
                path, f"Expected playbook {name} not found in any of "
                f"{[str(d) for d in PLAYBOOK_DIRS]}")

    def test_all_wiki_pages_frontmatter(self):
        valid_types = {
            "hardware", "codebase", "concept", "playbook", "source", "analysis"
        }
        all_md_files = kb_pages()
        self.assertGreaterEqual(len(all_md_files), 40)

        for md_file in all_md_files:
            content = md_file.read_text(encoding="utf-8")
            self.assertTrue(
                content.startswith("---"),
                f"File {md_file.relative_to(KB_DIR)} must start with YAML frontmatter (---)",
            )
            parts = content.split("---", 2)
            self.assertGreaterEqual(
                len(parts),
                3,
                f"File {md_file.relative_to(KB_DIR)} must have closing YAML frontmatter (---)",
            )
            frontmatter_raw = parts[1]
            try:
                fm = yaml.safe_load(frontmatter_raw)
            except (yaml.YAMLError, ValueError) as e:
                self.fail(
                    f"Invalid YAML frontmatter in {md_file.relative_to(KB_DIR)}: {e}"
                )

            self.assertIsInstance(
                fm, dict, f"Frontmatter in {md_file} must parse as dict")
            self.assertIn("title", fm, f"Missing title in {md_file}")
            self.assertIn("type", fm, f"Missing type in {md_file}")
            self.assertIn(fm["type"], valid_types,
                          f"Invalid type {fm.get(type)} in {md_file}")
            self.assertIn("tags", fm, f"Missing tags in {md_file}")
            self.assertIn("created", fm, f"Missing created date in {md_file}")
            self.assertIn("updated", fm, f"Missing updated date in {md_file}")
            self.assertIn("sources", fm, f"Missing sources count in {md_file}")
            self.assertIn("human_reviewed", fm,
                          f"Missing human_reviewed boolean in {md_file}")

    def test_codebase_subwikis_are_wikify_silos(self):
        """Each wiki/codebases/<repo>/ subwiki is a complete, pinned wikify-repo silo."""
        for sub in codebase_subwikis():
            rel = sub.relative_to(KB_DIR)
            index_fm = frontmatter(sub / "index.md")
            self.assertEqual(index_fm.get("slug"), sub.name,
                             f"{rel}/index.md must carry slug: {sub.name}")
            self.assertRegex(str(index_fm.get("commit", "")), _HEX40,
                             f"{rel}/index.md must pin a full commit sha")
            self.assertIn("okf_version", index_fm,
                          f"{rel}/index.md must declare okf_version")
            self.assertTrue((sub / "overview.md").is_file(),
                            f"{rel}/overview.md (entry page) must exist")
            self.assertTrue(list((sub / "concepts").glob("*.md")),
                            f"{rel}/concepts/ must hold at least one page")
            for page in [sub / "overview.md"] + list(
                (sub / "concepts").glob("*.md")) + list(
                    (sub / "doc-concepts").glob("*.md")) + list(
                        (sub / "catalog").rglob("*.md")):
                fm = frontmatter(page)
                self.assertIn(
                    "type", fm,
                    f"{page.relative_to(KB_DIR)} must carry wikify front matter"
                )
                if page.parent.name != "catalog" and "catalog" not in page.parts:
                    self.assertIn(
                        "title", fm,
                        f"{page.relative_to(KB_DIR)} must carry a title")
            # The hub page in wiki/codebases/ routes into the subwiki.
            hubs = [
                p for p in CODEBASES_DIR.glob("*.md")
                if f"{sub.name}/overview.md" in p.read_text(encoding="utf-8")
            ]
            self.assertTrue(
                hubs,
                f"no wiki/codebases/*.md hub page links to {rel}/overview.md")

    def test_internal_markdown_links_resolve(self):
        """Assert that all relative markdown links point to existing files.

        Subwiki pages are excluded: their citations (`catalog/<module>.md#<Symbol>`) resolve
        through wikify's symbol index, not through files, and `wikify finalize` is their gate.
        Links from KB pages into a subwiki (the hub's overview link) are still checked."""
        all_md_files = kb_pages() + [KB_DIR / "index.md"]
        link_pattern = re.compile(r"\[([^\]]+)\]\(([^\)]+)\)")

        broken_links = []
        for md_file in all_md_files:
            content = md_file.read_text(encoding="utf-8")
            # Strip fenced code blocks to avoid false positives in examples
            content_no_code = re.sub(r"```.*?```",
                                     "",
                                     content,
                                     flags=re.DOTALL)

            for match in link_pattern.finditer(content_no_code):
                _link_text, link_target = match.groups()
                # Skip external web links, email, anchors, and wikify's `src:` prose
                # citations (repo-relative doc paths resolved by `wikify finalize`).
                if link_target.startswith(
                    ("http://", "https://", "mailto:", "#", "src:")):
                    continue

                # Strip anchor fragments
                target_path_str = link_target.split("#")[0].strip()
                if not target_path_str:
                    continue

                target_resolved = (md_file.parent / target_path_str).resolve()
                if not target_resolved.exists():
                    broken_links.append((
                        str(md_file.relative_to(KB_DIR)),
                        link_target,
                        str(target_resolved),
                    ))

        self.assertEqual(
            broken_links,
            [],
            f"Found broken relative links in knowledgebase: {broken_links}",
        )

    def test_playbooks_target_imports_discovery(self):
        """Assert that playbooks declare target_imports in YAML frontmatter for dynamic discovery."""
        # `type: playbook` rather than the directory listing: pages/ holds the
        # unwiring playbooks alongside ninety pages that are not playbooks and
        # owe no target_imports.
        all_playbooks = [
            p for d in PLAYBOOK_DIRS for p in sorted(d.glob("*.md"))
            if (frontmatter(p) or {}).get("type") == "playbook"
        ]
        self.assertTrue(
            all_playbooks, "no playbooks found in any of "
            f"{[str(d) for d in PLAYBOOK_DIRS]}")
        discovered_targets = {}
        for pb in all_playbooks:
            content = pb.read_text(encoding="utf-8")
            parts = content.split("---", 2)
            self.assertGreaterEqual(len(parts), 3,
                                    f"Playbook {pb.name} missing frontmatter")
            fm = yaml.safe_load(parts[1])
            self.assertIn("target_imports", fm,
                          f"Playbook {pb.name} must declare target_imports")
            targets = fm["target_imports"]
            self.assertIsInstance(
                targets, list, f"target_imports in {pb.name} must be a list")
            self.assertGreater(len(targets), 0,
                               f"target_imports in {pb.name} cannot be empty")
            for t in targets:
                discovered_targets[t] = pb.name

        # Ensure major CUDA blockers are covered
        expected_triggers = [
            "flash_attn", "mamba_ssm", "triton", "apex", "deepspeed",
            "xformers"
        ]
        for trig in expected_triggers:
            self.assertIn(
                trig,
                discovered_targets,
                f"Expected trigger '{trig}' not found in any playbook's target_imports",
            )

    def test_knowledgebase_index_deterministic_validation(self):
        """Deterministically validates index.md page count, dates, and link integrity."""
        from package.data.knowledgebase.scripts import validate_kb

        errors = validate_kb.validate_index()
        self.assertEqual(errors, [], f"index.md validation failed: {errors}")

    def test_knowledgebase_log_deterministic_validation(self):
        """Deterministically validates log.md entry structure, dates, and order."""
        from package.data.knowledgebase.scripts import validate_kb

        errors = validate_kb.validate_log(check_git_diff=False)
        self.assertEqual(errors, [], f"log.md validation failed: {errors}")


if __name__ == "__main__":
    unittest.main()
