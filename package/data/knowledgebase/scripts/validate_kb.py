"""Deterministic validator for knowledge base index.md and log.md integrity.

index.md is a catalog: every page under wiki/ must be listed and every listed link must
resolve. It carries no page counts (they are implied by the tree, and a hand-kept number
conflicts on every rebase). log.md entries must use a schema operation token and be
ordered newest first.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

_KB_DIR = Path(__file__).resolve().parent.parent

_LOG_ENTRY_RE = re.compile(
    r"^##\s+\[(\d{4}-\d{2}-\d{2})\]\s+([\w-]+)\s+\|\s+(.+)$")
# The `<operation>` enum from SCHEMA.md ("log.md" section).
_LOG_OPERATIONS = ("ingest", "query", "lint", "manual")

# log.md records knowledge events, so tooling that merely reads or checks the
# wiki is not a loggable change. Paths under these prefixes are exempt.
_NON_CONTENT_PREFIXES = ("scripts/", )


def _paths(kb_dir: Path) -> tuple[Path, Path, Path]:
    return kb_dir / "index.md", kb_dir / "log.md", kb_dir / "wiki"


def get_codebase_subwikis(kb_dir: Path = _KB_DIR) -> list[Path]:
    """Returns codebase subwikis: wiki/codebases/<repo>/ directories with their own index.md.

    These are generated by wikify-repo (see SCHEMA.md, "Codebase subwikis"): they carry
    their own index and page schema, so index.md catalogs each one through a single entry
    (its overview.md) instead of listing every page inside it.
    """
    codebases = _paths(kb_dir)[2] / "codebases"
    if not codebases.is_dir():
        return []
    return sorted(p for p in codebases.iterdir()
                  if p.is_dir() and (p / "index.md").is_file())


def _in_subwiki(path: Path, subwikis: list[Path]) -> bool:
    return any(sub in path.parents for sub in subwikis)


def get_actual_wiki_pages(kb_dir: Path = _KB_DIR) -> list[Path]:
    """Returns all wiki markdown files excluding temporary/keep files, subwiki pages, and
    wikify's regenerated listing of the subwikis (wiki/codebases/index.md)."""
    wiki_dir = _paths(kb_dir)[2]
    subwikis = get_codebase_subwikis(kb_dir)
    listing = wiki_dir / "codebases" / "index.md"
    return sorted(p for p in wiki_dir.rglob("*.md")
                  if not p.name.startswith(".") and p.name != ".keep"
                  and p != listing and not _in_subwiki(p, subwikis))


def validate_index(kb_dir: Path = _KB_DIR) -> list[str]:
    """Validates that index.md catalogs every wiki page and links only to existing pages."""
    errors = []
    index_file, _, wiki_dir = _paths(kb_dir)
    if not index_file.exists():
        return [f"Missing index file at {index_file}"]

    content = index_file.read_text(encoding="utf-8")

    # Check that all actual pages are cataloged in index.md
    for page in get_actual_wiki_pages(kb_dir):
        rel_path = page.relative_to(kb_dir)
        # Check for relative link reference (e.g. (wiki/hardware/tpu-7x.md))
        if str(rel_path) not in content:
            errors.append(f"Wiki page not referenced in index.md: {rel_path}")

    # Check that every codebase subwiki is cataloged through its entry page
    for sub in get_codebase_subwikis(kb_dir):
        rel_dir = sub.relative_to(kb_dir)
        if f"{rel_dir}/overview.md" not in content:
            errors.append(
                f"Codebase subwiki not referenced in index.md: {rel_dir}/"
                " (link its overview.md)")

    # Check that all wiki links in index.md actually exist
    link_pattern = re.compile(r"\(wiki/([^)]+\.md)\)")
    for m in link_pattern.finditer(content):
        target = wiki_dir / m.group(1)
        if not target.exists():
            errors.append(
                f"index.md contains link to non-existent wiki file: wiki/{m.group(1)}"
            )

    return errors


def changed_kb_files(kb_dir: Path = _KB_DIR,
                     base: str | None = None) -> list[str]:
    """Knowledge-base files (repo-relative) changed in the working tree vs HEAD, or —
    with `base` — committed on this branch since its merge-base with `base`."""
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                         cwd=str(kb_dir),
                         capture_output=True,
                         text=True,
                         check=True).stdout.strip()
    rel = kb_dir.resolve().relative_to(Path(top).resolve()).as_posix()
    prefix = "" if rel == "." else rel + "/"
    rng = [f"{base}...HEAD"] if base else ["HEAD"]
    res = subprocess.run(["git", "diff", "--name-only", *rng],
                         cwd=top,
                         capture_output=True,
                         text=True,
                         check=True)
    return [
        f for f in res.stdout.splitlines() if f.startswith(prefix)
        and not f[len(prefix):].startswith(_NON_CONTENT_PREFIXES)
    ]


def validate_log(check_git_diff: bool = False,
                 kb_dir: Path = _KB_DIR,
                 base: str | None = None) -> list[str]:
    """Validates log.md entry formats, operation tokens, and ordering. With
    `check_git_diff`, also requires a log.md change alongside any other knowledge base
    change (working tree vs HEAD, or this branch vs `base`)."""
    errors = []
    _, log_file, _ = _paths(kb_dir)
    if not log_file.exists():
        return [f"Missing log file at {log_file}"]

    log_entries = []
    for line in log_file.read_text(encoding="utf-8").splitlines():
        m = _LOG_ENTRY_RE.match(line)
        if not m:
            continue
        date_str, action, desc = m.groups()
        try:
            entry_date = datetime.strptime(
                date_str, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        except ValueError:
            errors.append(f"Invalid ISO date in log.md entry: '{date_str}'")
            continue
        log_entries.append((entry_date, date_str, action, desc))

    if not log_entries:
        errors.append(
            "log.md contains no valid entries (format: '## [YYYY-MM-DD] action |"
            " desc')")
        return errors

    # Verify the operation token is one the schema allows
    for _, date_str, action, desc in log_entries:
        if action not in _LOG_OPERATIONS:
            errors.append(
                f"log.md entry '{date_str} | {desc}' uses operation '{action}';"
                f" allowed: {' | '.join(_LOG_OPERATIONS)}")

    # Verify reverse chronological ordering (newest first)
    for i in range(len(log_entries) - 1):
        curr_date, curr_str, _, curr_desc = log_entries[i]
        next_date, next_str, _, next_desc = log_entries[i + 1]
        if curr_date < next_date:
            errors.append(
                f"log.md entries out of chronological order: entry '{curr_str} |"
                f" {curr_desc}' precedes newer entry '{next_str} | {next_desc}'"
            )

    # A knowledge base change must come with a log entry
    if check_git_diff:
        try:
            kb_changed = changed_kb_files(kb_dir, base)
            if kb_changed and not any(
                    f.endswith("/log.md") or f == "log.md"
                    for f in kb_changed):
                errors.append(
                    "Knowledge base files were modified, but no accompanying entry was"
                    " added to log.md! Changed: " + ", ".join(kb_changed))
        except (subprocess.SubprocessError, OSError) as e:
            errors.append(f"Git diff inspection failed: {e}")

    return errors


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Validate Knowledge Base Index & Log")
    parser.add_argument(
        "--check-git",
        action="store_true",
        help="Require a log.md change alongside any other knowledge"
        " base change (working tree vs HEAD)")
    parser.add_argument(
        "--base",
        metavar="REF",
        help="With --check-git: compare this branch to REF"
        " (e.g. origin/main) instead of the working tree; implies"
        " --check-git")
    args = parser.parse_args()

    all_errors = []
    all_errors.extend(validate_index())
    all_errors.extend(
        validate_log(check_git_diff=args.check_git or bool(args.base),
                     base=args.base))

    if all_errors:
        print("❌ Knowledge Base Validation Failed:", file=sys.stderr)
        for err in all_errors:
            print(f"  - {err}", file=sys.stderr)
        sys.exit(1)

    print(f"✅ Knowledge Base is valid ({len(get_actual_wiki_pages())} pages"
          " cataloged in index.md, log entries well-formed).")


if __name__ == "__main__":
    main()
